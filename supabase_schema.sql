-- ==============================================================================
-- JARVIS: CHENNAI EVENT MAP — SUPABASE SCHEMA
-- ==============================================================================
-- Run in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Safe to re-run: every statement is idempotent.
--
-- Access model
--   * Visitors (anon key, in the browser) can only READ published events and venues.
--   * Every write goes through the FastAPI backend using the service-role key,
--     which bypasses RLS. Visitors cannot insert rows or upload files directly.
--   * Private intake data (submitter contact, raw model output, poster hash)
--     lives in `submissions`, which visitors can never read.

-- 1. ENUMS ---------------------------------------------------------------------
DO $$ BEGIN
    CREATE TYPE event_status AS ENUM ('review', 'published', 'hidden', 'expired');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE submission_source AS ENUM ('web_form', 'ingest', 'whatsapp_bot', 'instagram_share', 'admin');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
-- Older versions of this schema lacked 'ingest'
ALTER TYPE submission_source ADD VALUE IF NOT EXISTS 'ingest';

-- 2. VENUES --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.venues (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name        TEXT NOT NULL UNIQUE,
    area        TEXT NOT NULL,
    address     TEXT,
    lat         DOUBLE PRECISION NOT NULL,
    lng         DOUBLE PRECISION NOT NULL,
    category    TEXT DEFAULT 'general',
    is_verified BOOLEAN DEFAULT TRUE,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 3. EVENTS (public listing fields only) ---------------------------------------
CREATE TABLE IF NOT EXISTS public.events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Title, category, place and date may be blank while an event is in review
    -- (poster-only submissions); events_publishable below requires them to go live.
    title        TEXT CHECK (char_length(title) BETWEEN 1 AND 200),
    category     TEXT CHECK (category IN ('concerts', 'tech-events', 'college-culturals', 'movies', 'social-gatherings')),
    area         TEXT,
    venue        TEXT,
    date         TIMESTAMPTZ,
    end_date     TIMESTAMPTZ,
    price        INTEGER NOT NULL DEFAULT 0 CHECK (price >= 0),
    is_free      BOOLEAN NOT NULL DEFAULT TRUE,
    description  TEXT,
    image_url    TEXT,
    booking_link TEXT,
    lat          DOUBLE PRECISION,
    lng          DOUBLE PRECISION,
    is_featured  BOOLEAN NOT NULL DEFAULT FALSE,
    status       event_status NOT NULL DEFAULT 'review',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- Older versions defaulted new events straight to 'published'
ALTER TABLE public.events ALTER COLUMN status SET DEFAULT 'review';
ALTER TABLE public.events DROP COLUMN IF EXISTS source;

-- Poster-only submissions: details can be missing until review, never once published.
ALTER TABLE public.events ALTER COLUMN title    DROP NOT NULL;
ALTER TABLE public.events ALTER COLUMN category DROP NOT NULL;
ALTER TABLE public.events ALTER COLUMN area     DROP NOT NULL;
ALTER TABLE public.events ALTER COLUMN venue    DROP NOT NULL;
ALTER TABLE public.events ALTER COLUMN date     DROP NOT NULL;
ALTER TABLE public.events ALTER COLUMN lat      DROP NOT NULL;
ALTER TABLE public.events ALTER COLUMN lng      DROP NOT NULL;
ALTER TABLE public.events DROP CONSTRAINT IF EXISTS events_publishable;
ALTER TABLE public.events ADD CONSTRAINT events_publishable CHECK (
    status <> 'published' OR (
        title IS NOT NULL AND category IS NOT NULL AND venue IS NOT NULL AND venue <> ''
        AND area IS NOT NULL AND area <> '' AND date IS NOT NULL AND lat IS NOT NULL AND lng IS NOT NULL
    )
);

-- 4. SUBMISSIONS (private intake record, one per event) -------------------------
-- An older version had an unrelated `submissions` inbox table; replace it.
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'submissions' AND column_name = 'raw_poster_url') THEN
        DROP TABLE public.submissions;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.submissions (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id          BIGINT NOT NULL UNIQUE REFERENCES public.events(id) ON DELETE CASCADE,
    source            submission_source NOT NULL DEFAULT 'web_form',
    submitter_contact TEXT,
    poster_path       TEXT,                 -- object path inside the `posters` bucket
    poster_hash       TEXT UNIQUE,          -- sha256 of the image; blocks duplicate posters
    poster_fingerprint TEXT,                -- look-alike hash; catches resized/re-saved copies
    extracted_data    JSONB,                -- raw vision-model output, for auditing
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Older versions lacked the look-alike fingerprint
ALTER TABLE public.submissions ADD COLUMN IF NOT EXISTS poster_fingerprint TEXT;

-- 5. REPORTS -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reports (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         BIGINT NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    reason           TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 1000),
    reporter_ip_hash TEXT,
    status           TEXT NOT NULL DEFAULT 'pending',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. INDEXES -------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_events_status_date ON public.events (status, date);
CREATE INDEX IF NOT EXISTS idx_events_category    ON public.events (category);
CREATE INDEX IF NOT EXISTS idx_events_area        ON public.events (area);
CREATE INDEX IF NOT EXISTS idx_venues_area        ON public.venues (area);
CREATE INDEX IF NOT EXISTS idx_reports_event      ON public.reports (event_id);

-- 7. KEEP updated_at FRESH -----------------------------------------------------
CREATE OR REPLACE FUNCTION public.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS events_touch_updated_at ON public.events;
CREATE TRIGGER events_touch_updated_at
    BEFORE UPDATE ON public.events
    FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

-- 8. ROW LEVEL SECURITY --------------------------------------------------------
ALTER TABLE public.events      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.venues      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports     ENABLE ROW LEVEL SECURITY;

-- Remove policies from older versions of this schema (public writes, redundant service-role rules)
DROP POLICY IF EXISTS "Public can submit posters"               ON public.submissions;
DROP POLICY IF EXISTS "Public can submit reports"               ON public.reports;
DROP POLICY IF EXISTS "Service role full access on events"      ON public.events;
DROP POLICY IF EXISTS "Service role full access on submissions" ON public.submissions;
DROP POLICY IF EXISTS "Service role full access on venues"      ON public.venues;
DROP POLICY IF EXISTS "Service role full access on reports"     ON public.reports;

DROP POLICY IF EXISTS "Public can view published events" ON public.events;
CREATE POLICY "Public can view published events"
    ON public.events FOR SELECT
    USING (status = 'published');

DROP POLICY IF EXISTS "Public can view venues" ON public.venues;
CREATE POLICY "Public can view venues"
    ON public.venues FOR SELECT
    USING (true);

-- submissions and reports: no policies => no access for anon/authenticated.
-- The backend's service-role key bypasses RLS.

-- 9. POSTER STORAGE ------------------------------------------------------------
-- Public bucket: anyone can view a poster by URL; only the backend can upload.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('posters', 'posters', true, 10485760, ARRAY['image/jpeg', 'image/png', 'image/webp'])
ON CONFLICT (id) DO UPDATE
    SET public = EXCLUDED.public,
        file_size_limit = EXCLUDED.file_size_limit,
        allowed_mime_types = EXCLUDED.allowed_mime_types;

DROP POLICY IF EXISTS "Public can upload posters" ON storage.objects;
-- Public buckets serve files by URL without a SELECT policy; a broad SELECT
-- policy would also let anyone list every file in the bucket.
DROP POLICY IF EXISTS "Public Access to Posters"  ON storage.objects;
