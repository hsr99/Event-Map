-- Run this script in the Supabase SQL Editor (Dashboard -> SQL Editor -> New Query)
-- It creates the tables, indices, Row Level Security (RLS) policies, and storage setup.

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. ENUMS
DO $$ BEGIN
    CREATE TYPE event_status AS ENUM ('published', 'review', 'hidden', 'expired');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE submission_source AS ENUM ('web_form', 'whatsapp_bot', 'instagram_share', 'admin');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- 3. VENUES DIRECTORY TABLE
CREATE TABLE IF NOT EXISTS public.venues (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name TEXT NOT NULL UNIQUE,
    area TEXT NOT NULL,
    address TEXT,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    category TEXT DEFAULT 'general',
    is_verified BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. EVENTS TABLE (Core Public Event Listings)
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    area TEXT NOT NULL,
    venue TEXT NOT NULL,
    date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ,
    price INTEGER DEFAULT 0,
    is_free BOOLEAN DEFAULT TRUE,
    description TEXT,
    image_url TEXT,
    booking_link TEXT,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    is_featured BOOLEAN DEFAULT FALSE,
    status event_status DEFAULT 'published',
    source submission_source DEFAULT 'admin',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. SUBMISSIONS / INBOX TABLE (Cloud Intake for Posters)
CREATE TABLE IF NOT EXISTS public.submissions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    source submission_source DEFAULT 'web_form',
    submitter_contact TEXT,
    raw_poster_url TEXT,
    source_url TEXT,
    extracted_data JSONB,
    status event_status DEFAULT 'review',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. COMMUNITY REPORTS TABLE (Spam / Inaccuracy Flags)
CREATE TABLE IF NOT EXISTS public.reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT REFERENCES public.events(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    reporter_ip_hash TEXT,
    status TEXT DEFAULT 'pending',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. PERFORMANCE INDICES
CREATE INDEX IF NOT EXISTS idx_events_date ON public.events (date);
CREATE INDEX IF NOT EXISTS idx_events_category ON public.events (category);
CREATE INDEX IF NOT EXISTS idx_events_area ON public.events (area);
CREATE INDEX IF NOT EXISTS idx_events_status ON public.events (status);
CREATE INDEX IF NOT EXISTS idx_events_coords ON public.events (lat, lng);
CREATE INDEX IF NOT EXISTS idx_venues_area ON public.venues (area);

-- 8. ROW LEVEL SECURITY (RLS) POLICIES
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.venues ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;

-- Events: Anyone can view published events
CREATE POLICY "Public can view published events"
    ON public.events FOR SELECT
    USING (status = 'published');

-- Venues: Anyone can view venues directory
CREATE POLICY "Public can view venues"
    ON public.venues FOR SELECT
    USING (true);

-- Submissions: Anyone can submit a poster (intake)
CREATE POLICY "Public can submit posters"
    ON public.submissions FOR INSERT
    WITH CHECK (true);

-- Reports: Anyone can report an event
CREATE POLICY "Public can submit reports"
    ON public.reports FOR INSERT
    WITH CHECK (true);

-- Service Role (Backend Worker) has full access
CREATE POLICY "Service role full access on events"
    ON public.events FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Service role full access on submissions"
    ON public.submissions FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Service role full access on venues"
    ON public.venues FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Service role full access on reports"
    ON public.reports FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

-- 9. SUPABASE STORAGE BUCKET FOR POSTERS
INSERT INTO storage.buckets (id, name, public)
VALUES ('posters', 'posters', true)
ON CONFLICT (id) DO NOTHING;

-- Public can view posters in storage
CREATE POLICY "Public Access to Posters"
    ON storage.objects FOR SELECT
    USING (bucket_id = 'posters');

-- Public can upload posters into storage
CREATE POLICY "Public can upload posters"
    ON storage.objects FOR INSERT
    WITH CHECK (bucket_id = 'posters');
